final class WatertightRegressionTests: XCTestCase {
    func testKochUnionWithTriangulatedRing() throws {
        // Projected triangle area can round to a positive value even when the
        // corresponding 3D triangle is degenerate. Keep the original coordinates.
        let points = kochOutline.map { Vector($0.0, $0.1, 0) }
        let polygon = try XCTUnwrap(Polygon(points))
        for polygon in [polygon, polygon.inverted()] {
            let triangles = polygon.triangulate()
            XCTAssertEqual(triangles.count, polygon.vertices.count - 2)
            XCTAssertTrue(triangles.allSatisfy { !verticesAreDegenerate($0.vertices) })
            XCTAssertEqual(triangles.reduce(0) { $0 + $1.area }, polygon.area, accuracy: epsilon)
        }
        let plate = Mesh.extrude(Path(points.map { .point($0) } + [.point(points[0])]), depth: 3)
        let top = try XCTUnwrap(points.max(by: { $0.y < $1.y }))
        let ring = triangulatedRing(at: top)
        XCTAssertTrue(plate.isWatertight)
        XCTAssertTrue(ring.isWatertight)
        let joined = plate.union(ring)
        let repaired = joined.makeWatertight()
        XCTAssertTrue(repaired.isWatertight)
        let counts = edgeCounts(repaired.polygons)
        XCTAssertEqual(counts.open, 0)
        XCTAssertEqual(counts.overused, 0)
        XCTAssertEqual(repaired.signedVolume, joined.signedVolume, accuracy: epsilon)
    }

    func testRosetteAndSunUnionRepairWithTriangulatedRing() throws {
        for (name, sector, repeats) in [("Rosette", rosetteSector, 6), ("Sun", sunSector, 6)] {
            let points = (0 ..< repeats).flatMap { i in
                let a = Double(i) * .pi / 3
                return sector.map { x, y in Vector(x * cos(a) - y * sin(a), x * sin(a) + y * cos(a), 0) }
            }
            let plate = Mesh.extrude(Path(points.map { .point($0) } + [.point(points[0])]), depth: 3)
            let top = try XCTUnwrap(points.max(by: { $0.y < $1.y }))
            let ring = triangulatedRing(at: top)
            let joined = plate.union(ring)
            let repaired = joined.makeWatertight()
            XCTAssertTrue(plate.isWatertight, name)
            XCTAssertTrue(ring.isWatertight, name)
            XCTAssertTrue(repaired.isWatertight, name)
            let counts = edgeCounts(repaired.polygons)
            XCTAssertEqual(counts.open, 0, name)
            XCTAssertEqual(counts.overused, 0, name)
            XCTAssertEqual(repaired.bounds, joined.bounds, name)
            XCTAssertEqual(repaired.signedVolume, joined.signedVolume, accuracy: 1e-6, name)
            XCTAssertEqual(repaired.makeWatertight(), repaired, name)
            let offset = Vector(0, -1, 0)
            let invalid = repaired.polygons.filter { verticesAreDegenerate($0.vertices.translated(by: offset)) }
            XCTAssertTrue(invalid.isEmpty, "\(name): \(invalid.count) degenerate translated polygons")
            if invalid.isEmpty {
                XCTAssertTrue(repaired.translated(by: offset).isWatertight, name)
            }
        }
    }

    private func edgeCounts(_ polygons: [Euclid.Polygon]) -> (open: Int, overused: Int) {
        var uses = [LineSegment: Int]()
        for polygon in polygons {
            for edge in polygon.orderedEdges {
                uses[LineSegment(undirected: edge), default: 0] += 1
            }
        }
        return (uses.values.filter { $0 == 1 }.count, uses.values.filter { $0 > 2 }.count)
    }

    private func triangulatedRing(at center: Vector) -> Mesh {
        let sides = 24
        func circle(_ radius: Double) -> [Vector] {
            (0 ..< sides).map { i in
                let angle = 2 * .pi * Double(i) / Double(sides)
                return Vector(cos(angle) * radius, sin(angle) * radius)
            }
        }
        let outer = circle(4), hole = circle(1.8)
        func at(_ p: Vector, _ z: Double) -> Vector { Vector(p.x, p.y, z) }
        var triangles = [[Vector]]()
        for (z, up) in [(-1.5, false), (1.5, true)] {
            for i in 0 ..< sides {
                let j = (i + 1) % sides
                for triangle in [[outer[i], outer[j], hole[j]], [outer[i], hole[j], hole[i]]] {
                    let points = triangle.map { at($0, z) }
                    triangles.append(up ? points : points.reversed())
                }
            }
        }
        for (loop, out) in [(outer, true), (hole, false)] {
            for i in 0 ..< sides {
                let j = (i + 1) % sides
                let corners = [at(loop[i], 1.5), at(loop[i], -1.5), at(loop[j], -1.5), at(loop[j], 1.5)]
                let q = out ? corners : corners.reversed()
                if (q[0] - q[2]).lengthSquared <= (q[1] - q[3]).lengthSquared {
                    triangles += [[q[0], q[1], q[2]], [q[0], q[2], q[3]]]
                } else {
                    triangles += [[q[1], q[2], q[3]], [q[1], q[3], q[0]]]
                }
            }
        }
        return Mesh(triangles.map { Polygon($0)! }).translated(by: Vector(center.x, center.y, 0))
    }

    func testRepairRemovesCollapsedSliverWithoutAddingDuplicateCap() throws {
        let a = Vector(-1, -1, 0), b = Vector(1, 1, 0), c = Vector(0, 1e-12, 0)
        let sliver = try XCTUnwrap(Polygon([a, b, c]))
        let upper = try XCTUnwrap(Polygon([a, c, b, [-1, 1, 0]]))
        let lower = try XCTUnwrap(Polygon([a, [1, -1, 0], b, c]))
        let polygons = [upper, lower, sliver]
        let repaired = polygons.removingOverlappingSlivers { false }
        XCTAssertEqual(repaired, [upper, lower])
    }

    func testRepairPreservesThinFacesWithoutOverusedEdges() throws {
        let sliver = try XCTUnwrap(Polygon([
            Vector(-1, -1, 0), Vector(1, 1, 0), Vector(0, 1e-12, 0),
        ]))
        let polygons = [sliver, sliver.inverted()]
        XCTAssertEqual(polygons.removingOverlappingSlivers { false }, polygons)
    }

    func testRepairPreservesNonCollapsedOverlappingFaces() throws {
        let triangle = try XCTUnwrap(Polygon([Vector(0, 0), Vector(1, 0), Vector(0, 1)]))
        let polygons = [triangle, triangle, triangle]
        XCTAssertEqual(polygons.removingOverlappingSlivers { false }, polygons)
    }

